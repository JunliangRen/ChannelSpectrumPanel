inline std::wstring localized_error(HWND window,const char* error){
    const int count=MultiByteToWideChar(CP_UTF8,0,error,-1,nullptr,0);
    if(count<=0)return tr(window,L"Operation failed.");
    std::wstring wide(size_t(count),L'\0');MultiByteToWideChar(CP_UTF8,0,error,-1,wide.data(),count);wide.resize(count-1);
    const auto* translated=tr(window,wide.c_str());
    if(translated!=wide.c_str())return translated;
    return std::wstring(tr(window,L"Operation failed."))+L"\n\n"+wide;
}
// Error reporting must not throw back through a Win32 dialog callback on allocation failure.
inline void show_localized_error(HWND window,const char* error,const wchar_t* title) noexcept {
    try {auto text=localized_error(window,error);MessageBoxW(window,text.c_str(),tr(window,title),MB_OK|MB_ICONERROR);}
    catch(...) {MessageBoxW(window,tr(window,L"Operation failed."),tr(window,title),MB_OK|MB_ICONERROR);}
}

