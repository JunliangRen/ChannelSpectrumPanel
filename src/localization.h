inline unsigned ui_language(HWND window) noexcept {
    for(HWND w=window;w;w=GetParent(w))if(auto value=GetProp(w,L"CspUiLanguage")){
        auto n=reinterpret_cast<ULONG_PTR>(value);return n>=1 && n<=3?unsigned(n-1):0;
    }
    return 0;
}
